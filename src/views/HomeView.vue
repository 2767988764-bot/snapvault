const morphOn = ref(false)
const morphVars = ref({})
const pickerEl = ref(null)
const tagBoxEl = ref(null)

// 容器在 .page-root 中的布局位置（不随 hover 的 translate/scale 变化）
function offsetInRoot(el) {
  const root = document.querySelector('.page-root')
  let left = 0
  let top = 0
  let node = el
  while (node && node !== root) {
    left += node.offsetLeft
    top += node.offsetTop
    node = node.offsetParent
  }
  return { left, top }
}

// 把 rgb(...) 计算色转成带透明度的颜色
function withAlpha(rgb, a) {
  const m = String(rgb).match(/\d+(\.\d+)?/g)
  return m && m.length >= 3 ? `rgba(${m[0]}, ${m[1]}, ${m[2]}, ${a})` : rgb
}

// 由点击的容器矩形算到浮层最终矩形的变形参数
function startMorph(srcEl, dstEl) {
  if (!srcEl || !dstEl) return
  const s = srcEl.getBoundingClientRect()
  const d = dstEl.getBoundingClientRect()
  if (!d.width || !d.height) return
  morphVars.value = {
    '--mx': `${(s.left - d.left).toFixed(1)}px`,
    '--my': `${(s.top - d.top).toFixed(1)}px`,
    '--msx': (s.width / d.width).toFixed(4),
    '--msy': (s.height / d.height).toFixed(4),
  }
  morphOn.value = true
}

function openScansPicker() {
  return openPicker('scans', document.querySelector('[data-pencil-name="RecentScansCard"]'))
}

function openOpenedPicker() {
  return openPicker('opened', document.querySelector('[data-pencil-name="RecentlyOpenedCard"]'))
}

async function openPicker(kind, srcEl) {
  morphOn.value = false
  overlayPos.value = offsetInRoot(srcEl)
  overlay.value = kind
  await nextTick()
  startMorph(srcEl, pickerEl.value)
}

// 头部与配色跟随被点击的 StickyNote
async function openTag(e) {
  const note = e.currentTarget
  const accent = getComputedStyle(note.querySelector('[data-pencil-name="NoteBar"]')).backgroundColor
  tagData.value = {
    name: note.querySelector('[data-pencil-name="NoteLabel"]')?.textContent.trim() || 'tag',
    count: note.querySelector('[data-pencil-name="NoteCount"]')?.textContent.trim() || '',
    theme: {
      bg: getComputedStyle(note).backgroundColor,
      accent,
      divider: withAlpha(accent, 0.2),
      metaColor: withAlpha(accent, 0.6),
    },
  }
  morphOn.value = false
  overlay.value = 'tag'
  await nextTick()
  startMorph(note, tagBoxEl.value)
}

function closeOverlay() {
  overlay.value = null
  morphOn.value = false
  morphVars.value = {}
}

function openDocument() {
  closeOverlay()
  router.push('/document-detail')
}

function openLibrary() {
  closeOverlay()
  router.push('/library')
}
